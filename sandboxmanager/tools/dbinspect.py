# --- output helpers ---------------------------------------------------------

_COLOR = sys.stdout.isatty() and not os.environ.get("NO_COLOR")


def _c(code: str, s: str) -> str:
    return f"\033[{code}m{s}\033[0m" if _COLOR else s


bold = lambda s: _c("1", s)  # noqa: E731
dim = lambda s: _c("2", s)  # noqa: E731
red = lambda s: _c("31", s)  # noqa: E731
green = lambda s: _c("32", s)  # noqa: E731
yellow = lambda s: _c("33", s)  # noqa: E731

STATUS_COLOR = {
    "Ready": green, "completed": green, "ok": green, "Paused": dim,
    "NotReady": yellow, "Deleting": yellow, "Pausing": yellow, "Resuming": yellow, "running": yellow, "timed_out": yellow, "warn": yellow,
    "Expired": dim, "Missing": red, "error": red, "problem": red,
}


def colorize(value: str) -> str:
    return STATUS_COLOR.get(value, str)(value)


def heading(text: str) -> None:
    print("\n" + bold(text))


def table(rows: Sequence[Dict[str, Any]], columns: Sequence[str], *, max_width: int = 60) -> None:
    if not rows:
        print(dim("  (none)"))
        return
    cells = [[_fmt(r.get(c), max_width) for c in columns] for r in rows]
    widths = [max(len(c), *(len(row[i]) for row in cells)) for i, c in enumerate(columns)]
    print("  " + "  ".join(dim(c.ljust(w)) for c, w in zip(columns, widths)))
    for row in cells:
        print("  " + "  ".join(colorize(v) + " " * (w - len(v)) for v, w in zip(row, widths)))


def _fmt(value: Any, max_width: int) -> str:
    if value is None:
        s = "-"
    elif isinstance(value, bool):
        s = "yes" if value else "no"
    elif isinstance(value, list):
        s = " ".join(str(v) for v in value)
    else:
        s = str(value)
    s = s.replace("\n", "\\n")
    return s if len(s) <= max_width else s[: max_width - 1] + "…"


def parse_time(value: Optional[str]) -> Optional[datetime]:
    if not value:
        return None
    value = value.replace("Z", "+00:00")
    if "." in value:  # Python 3.9 accepts only exactly 3 or 6 fractional digits
        head, rest = value.split(".", 1)
        n = len(rest) - len(rest.lstrip("0123456789"))
        value = f"{head}.{rest[:n][:6].ljust(6, '0')}{rest[n:]}"
    return datetime.fromisoformat(value)


def relative(value: Optional[str]) -> Optional[str]:
    """'4m12s ago' / 'in 3m' for an ISO timestamp."""
    t = parse_time(value)
    if t is None:
        return None
    secs = int((t - datetime.now(timezone.utc)).total_seconds())
    span = _span(abs(secs))
    return f"in {span}" if secs > 0 else f"{span} ago"


def _span(secs: int) -> str:
    if secs < 60:
        return f"{secs}s"
    if secs < 3600:
        return f"{secs // 60}m{secs % 60:02d}s"
    if secs < 86400:
        return f"{secs // 3600}h{(secs % 3600) // 60:02d}m"
    return f"{secs // 86400}d{(secs % 86400) // 3600}h"


def short(uuid: Optional[str]) -> Optional[str]:
    return uuid[:8] if uuid else uuid


# --- data access ------------------------------------------------------------


def kubectl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    if not shutil.which("kubectl"):
        sys.exit("dbinspect: kubectl not found on PATH")
    cmd = ["kubectl"] + (["--context", KUBE_CONTEXT] if KUBE_CONTEXT else []) + list(args)
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if check and proc.returncode != 0:
        sys.exit(f"dbinspect: {' '.join(cmd[:6])}... failed:\n{proc.stderr.strip()}")
    return proc


def query(sql: str) -> List[Dict[str, Any]]:
    """Run a read-only SELECT and return its rows as dicts."""
    wrapped = f"SELECT coalesce(json_agg(q), '[]'::json) FROM ({sql.strip().rstrip(';')}) q"
    proc = kubectl(
        "-n", NAMESPACE, "exec", POD, "--",
        "env", "PGOPTIONS=-c default_transaction_read_only=on",
        "psql", "-U", DB_USER, "-d", DB_NAME, "-v", "ON_ERROR_STOP=1", "-tAX", "-c", wrapped,
        check=False,
    )
    if proc.returncode != 0:
        err = proc.stderr.strip()
        if "NotFound" in err or "not found" in err:
            sys.exit(f"dbinspect: can't reach pod {NAMESPACE}/{POD}. Is the cluster up? (colima status, k3d cluster list)\n{err}")
        sys.exit(f"dbinspect: query failed:\n{err}")
    return json.loads(proc.stdout or "[]")


def one(sql: str) -> Dict[str, Any]:
    rows = query(sql)
    return rows[0] if rows else {}


def live_sandboxes() -> Dict[str, Dict[str, Any]]:
    """Sandbox objects created by the API, keyed by sandbox id, with summarized status."""
    proc = kubectl("get", SANDBOX_RESOURCE, "-A", "-l", SANDBOX_LABEL, "-o", "json", check=False)
    if proc.returncode != 0:
        print(yellow(f"warning: couldn't read Sandboxes from the cluster: {proc.stderr.strip()}"), file=sys.stderr)
        return {}
    out = {}
    for item in json.loads(proc.stdout).get("items", []):
        meta, spec = item["metadata"], item.get("spec", {})
        conditions = {c.get("type"): c for c in item.get("status", {}).get("conditions", [])}
        ready = conditions.get("Ready", {})
        susp = conditions.get("Suspended", {})
        mode = spec.get("operatingMode") or "Running"
        if meta.get("deletionTimestamp"):
            status = "Deleting"
        elif mode == "Suspended":
            # Paused only once Suspended=True is reported for the current spec.
            done = susp.get("status") == "True" and susp.get("observedGeneration") == meta.get("generation")
            status = "Paused" if done else "Pausing"
        else:
            status = "Ready" if ready.get("status") == "True" else "NotReady"
        sid = meta.get("labels", {}).get(SANDBOX_LABEL)
        out[sid] = {
            "name": meta["name"],
            "namespace": meta["namespace"],
            "status": status,
            "shutdown_time": spec.get("shutdownTime"),
            "operating_mode": mode,
            "ready_changed": ready.get("lastTransitionTime"),
        }
    return out


def pvc_names() -> Optional[set]:
    """Names of the API's sandbox PVCs (excluding ones already being deleted),
    or None if they can't be read."""
    proc = kubectl("get", "pvc", "-A", "-l", SANDBOX_LABEL, "-o", "json", check=False)
    if proc.returncode != 0:
        print(yellow(f"warning: couldn't read PVCs from the cluster: {proc.stderr.strip()}"), file=sys.stderr)
        return None
    return {item["metadata"]["name"] for item in json.loads(proc.stdout).get("items", [])
            if not item["metadata"].get("deletionTimestamp")}


def status_for(row: Dict[str, Any], live: Dict[str, Dict[str, Any]]) -> str:
    """Same rules as the API's sandbox status."""
    if row.get("deleted_at"):
        return "Deleted"
    obj = live.get(row["sandbox_id"])
    if obj:
        resumed = parse_time(row.get("resumed_at"))
        changed = parse_time(obj["ready_changed"])
        if obj["status"] == "NotReady" and resumed and (not changed or changed < resumed.replace(microsecond=0)):
            return "Resuming"
        return obj["status"]
    expires = parse_time(row.get("expires_at"))
    if expires and expires <= datetime.now(timezone.utc):
        return "Expired"
    return "Missing"


def resolve(table_name: str, column: str, prefix: str) -> str:
    """Expand an id prefix to the full id, or exit with a helpful message."""
    p = prefix.lower().replace("'", "")
    rows = query(f"SELECT {column}::text AS id FROM {table_name} WHERE {column}::text LIKE '{p}%' LIMIT 5")
    if not rows:
        sys.exit(f"dbinspect: no {table_name} row with id starting {prefix!r}")
    if len(rows) > 1:
        sys.exit(f"dbinspect: {prefix!r} is ambiguous: " + ", ".join(r["id"] for r in rows))
    return rows[0]["id"]


