def cmd_overview(_: argparse.Namespace) -> None:
    sizes = query("""
        SELECT c.relname AS table, c.reltuples::bigint AS est_rows,
               pg_size_pretty(pg_total_relation_size(c.oid)) AS size
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname""")
    counts = one("""
        SELECT (SELECT count(*) FROM notes) AS notes,
               (SELECT count(*) FROM sandboxes) AS sandboxes,
               (SELECT count(*) FROM executions) AS executions""")
    heading(f"Database {DB_NAME} on {NAMESPACE}/{POD}")
    for s in sizes:
        s["rows"] = counts.get(s["table"], s["est_rows"])
        s["what it holds"] = TABLE_DOCS.get(s["table"], ("",))[0].split(". ")[0]
    table(sizes, ["table", "rows", "size", "what it holds"], max_width=90)

    rows = query("SELECT sandbox_id::text, expires_at, ttl_seconds, deleted_at, resumed_at FROM sandboxes")
    live = live_sandboxes()
    by_status: Dict[str, int] = {}
    for r in rows:
        st = status_for(r, live)
        by_status[st] = by_status.get(st, 0) + 1
    heading("Sandboxes by live status")
    table([{"status": k, "count": v} for k, v in sorted(by_status.items())], ["status", "count"])

    heading("Executions by status")
    table(query("""
        SELECT status, count(*) AS count,
               round(avg(extract(epoch FROM finished_at - started_at))::numeric, 2) AS avg_seconds,
               max(started_at) AS latest
        FROM executions GROUP BY status ORDER BY status"""), ["status", "count", "avg_seconds", "latest"])

    problems = run_checks(quiet=True)
    heading("Health")
    if problems:
        print(f"  {red(str(problems))} issue(s) found; run `dbinspect check` for details")
    else:
        print("  " + green("ok") + dim(" (DB and cluster agree)"))
    print(dim("\nMore: schema | sandboxes | sandbox <id> | executions | execution <id> | check | sql"))


def cmd_schema(_: argparse.Namespace) -> None:
    columns = query("""
        SELECT c.relname AS table_name, a.attname AS column_name,
               format_type(a.atttypid, a.atttypmod) AS data_type,
               NOT a.attnotnull AS nullable, pg_get_expr(d.adbin, d.adrelid) AS column_default
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid AND c.relkind = 'r'
        JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attnum > 0 AND NOT a.attisdropped
        ORDER BY c.relname, a.attnum""")
    keys = query("""
        SELECT conrelid::regclass::text AS table, conname AS name, pg_get_constraintdef(oid) AS definition
        FROM pg_constraint WHERE connamespace = 'public'::regnamespace ORDER BY conrelid::regclass::text, contype""")
    indexes = query("""
        SELECT tablename AS table, indexname AS name, indexdef AS definition
        FROM pg_indexes WHERE schemaname = 'public' ORDER BY tablename, indexname""")

    width = min(shutil.get_terminal_size((100, 20)).columns, 120)
    for name in sorted({c["table_name"] for c in columns}):
        doc, col_docs = TABLE_DOCS.get(name, ("", {}))
        heading(f"{name}")
        if doc:
            print(textwrap.fill(doc, width - 2, initial_indent="  ", subsequent_indent="  "))
        print()
        cols = [c for c in columns if c["table_name"] == name]
        rows = [
            {
                "column": c["column_name"],
                "type": c["data_type"],
                "null": c["nullable"],
                "default": c["column_default"],
            }
            for c in cols
        ]
        table(rows, ["column", "type", "null", "default"])
        documented = [c["column_name"] for c in cols if c["column_name"] in col_docs]
        if documented:
            pad = max(len(n) for n in documented) + 4
            print()
            for n in documented:
                print(textwrap.fill(col_docs[n], width - 2, initial_indent=f"  {n.ljust(pad - 2)}",
                                    subsequent_indent=" " * pad))
        for k in keys:
            if k["table"] == name:
                print(dim(f"  constraint {k['name']}: ") + k["definition"])
        for i in indexes:
            if i["table"] == name and not i["name"].endswith("_pkey"):
                print(dim(f"  index {i['name']}: ") + i["definition"].split(" USING ")[-1])
    heading("Relationships")
    print("  sandboxes 1 ── * executions   (executions.sandbox_id → sandboxes.sandbox_id, ON DELETE CASCADE)")
    print("  sandboxes.name  ⇄  Sandbox object + pod in the cluster (label webapp/sandbox-id=<sandbox_id>)")


def cmd_sandboxes(args: argparse.Namespace) -> None:
    rows = query("""
        SELECT s.sandbox_id::text, s.name, s.namespace, s.created_at, s.ttl_seconds, s.expires_at, s.deleted_at,
               s.operating_mode, s.paused_at, s.resumed_at, count(e.*) AS execs, max(e.started_at) AS last_exec
        FROM sandboxes s LEFT JOIN executions e USING (sandbox_id)
        GROUP BY s.sandbox_id ORDER BY s.created_at""")
    live = live_sandboxes()
    for r in rows:
        r["status"] = status_for(r, live)
        r["id"] = short(r["sandbox_id"])
        r["created"] = relative(r["created_at"])
        r["expires"] = relative(r["expires_at"]) if r["expires_at"] else "never"
        r["ttl"] = f"{r['ttl_seconds']}s" if r["ttl_seconds"] else "-"
        r["last_exec"] = relative(r["last_exec"])
        r["mode"] = "paused " + relative(r["paused_at"]) if r["paused_at"] else r["operating_mode"]
    if args.status:
        rows = [r for r in rows if r["status"].lower() == args.status.lower()]
    heading(f"Sandboxes ({len(rows)})")
    table(rows, ["id", "status", "mode", "namespace", "created", "ttl", "expires", "execs", "last_exec"])
    orphans = [sid for sid in live if sid not in {r["sandbox_id"] for r in rows}]
    if orphans and not args.status:
        print(yellow(f"\n  {len(orphans)} Sandbox object(s) in the cluster have no row; see `dbinspect check`"))


def cmd_sandbox(args: argparse.Namespace) -> None:
    sid = resolve("sandboxes", "sandbox_id", args.id)
    row = one(f"SELECT sandbox_id::text, * FROM sandboxes WHERE sandbox_id = '{sid}'")
    live = live_sandboxes()
    obj = live.get(sid)
    heading(f"Sandbox {sid}")
    fields = [
        ("status", status_for(row, live)),
        ("name", row["name"]),
        ("namespace", row["namespace"]),
        ("created_at", f"{row['created_at']}  ({relative(row['created_at'])})"),
        ("ttl_seconds", row["ttl_seconds"] or "none (legacy, never expires)"),
        ("mode", row["operating_mode"] + (f" since {row['paused_at']}  ({relative(row['paused_at'])})" if row["paused_at"] else "")),
        ("paused_ttl", f"{row['paused_ttl_seconds']}s" if row["paused_ttl_seconds"] else "none (legacy, can't pause)"),
        ("expires_at", f"{row['expires_at']}  ({relative(row['expires_at'])})" if row["expires_at"] else "never"),
        ("cluster", f"{obj['namespace']}/{obj['name']} operatingMode={obj['operating_mode']} shutdownTime={obj['shutdown_time']}"
         if obj else "no Sandbox object"),
    ]
    for k, v in fields:
        print(f"  {dim(k.ljust(12))} {colorize(str(v)) if k == 'status' else v}")
    if obj and row["expires_at"] and obj["shutdown_time"]:
        if parse_time(obj["shutdown_time"]) != parse_time(row["expires_at"]):
            print(yellow("  note: DB expires_at and cluster shutdownTime differ"))
    heading("Definition (as created)")
    print(textwrap.indent(row["definition"].rstrip(), "  "))
    args.sandbox = sid
    args.limit = args.limit or 20
    cmd_executions(args, title=f"Executions (latest {args.limit})")


def cmd_executions(args: argparse.Namespace, title: Optional[str] = None) -> None:
    where = ""
    if getattr(args, "sandbox", None):
        where = f"WHERE sandbox_id = '{resolve('sandboxes', 'sandbox_id', args.sandbox)}'"
    rows = query(f"""
        SELECT execution_id::text, sandbox_id::text, command, status, exit_code, started_at,
               round(extract(epoch FROM coalesce(finished_at, now()) - started_at)::numeric, 2) AS seconds,
               length(stdout) AS stdout_bytes, length(stderr) AS stderr_bytes,
               stdout_truncated OR stderr_truncated AS truncated,
               left(stdout, 80) AS stdout
        FROM executions {where} ORDER BY started_at DESC LIMIT {int(args.limit or 20)}""")
    for r in rows:
        r["id"], r["sandbox"], r["started"] = short(r["execution_id"]), short(r["sandbox_id"]), relative(r["started_at"])
    heading(title or f"Executions (latest {len(rows)})")
    table(rows, ["id", "sandbox", "status", "exit_code", "started", "seconds", "command", "stdout"], max_width=40)


def cmd_execution(args: argparse.Namespace) -> None:
    eid = resolve("executions", "execution_id", args.id)
    r = one(f"""SELECT execution_id::text, sandbox_id::text, *,
                       extract(epoch FROM finished_at - started_at) AS seconds
                FROM executions WHERE execution_id = '{eid}'""")
    heading(f"Execution {eid}")
    for k in ("sandbox_id", "pod", "command", "status", "exit_code", "started_at", "finished_at", "seconds"):
        v = r[k]
        if k == "command":
            v = json.dumps(v)
        print(f"  {dim(k.ljust(12))} {colorize(str(v)) if k == 'status' else v}")
    for stream in ("stdout", "stderr"):
        trunc = " (truncated at 1 MiB)" if r[f"{stream}_truncated"] else ""
        heading(f"{stream} ({len(r[stream])} bytes{trunc})")
        print(textwrap.indent(r[stream].rstrip("\n"), "  ") if r[stream] else dim("  (empty)"))


def run_checks(quiet: bool = False) -> int:
    """Cross-check the DB against the cluster. Returns the number of problems."""
    rows = query("""SELECT sandbox_id::text, name, namespace, ttl_seconds, expires_at, deleted_at, volume_name,
                          operating_mode, resumed_at FROM sandboxes""")
    live = live_sandboxes()
    now = datetime.now(timezone.utc)
    problems = 0
    results = []

    def report(level: str, title: str, items: List[str], explain: str) -> None:
        nonlocal problems
        if level == "problem" and items:
            problems += len(items)
        results.append((level if items else "ok", title, items, explain))

    known = {r["sandbox_id"] for r in rows}
    report("problem", "Sandbox objects in the cluster with no DB row",
           [f"{v['namespace']}/{v['name']}" for k, v in live.items() if k not in known],
           "The API can't see or delete these. Usually a create whose DB commit failed. "
           "Remove with: kubectl -n <ns> delete sandboxes.agents.x-k8s.io <name>")
    report("info", "Rows whose sandbox expired (object deleted by the TTL controller)",
           [short(r["sandbox_id"]) for r in rows if r["sandbox_id"] not in live and status_for(r, live) == "Expired"],
           "Expected. The row stays as history until DELETE /sandboxes/{id}.")
    report("problem", "Rows whose sandbox is gone but not because of its TTL (Missing)",
           [short(r["sandbox_id"]) for r in rows if status_for(r, live) == "Missing"],
           "Deleted outside the API (e.g. kubectl) or never expired via TTL. DELETE /sandboxes/{id} cleans the row.")
    report("warn", "Rows past expires_at whose object still exists",
           [short(r["sandbox_id"]) for r in rows
            if r["sandbox_id"] in live and r["expires_at"] and parse_time(r["expires_at"]) < now
            and live[r["sandbox_id"]]["status"] != "Deleting"],
           "The controller should delete these shortly; if it persists, check the agent-sandbox controller.")
    report("warn", "DB expires_at differs from the cluster's shutdownTime",
           [short(r["sandbox_id"]) for r in rows
            if r["sandbox_id"] in live and r["expires_at"] and live[r["sandbox_id"]]["shutdown_time"]
            and parse_time(live[r["sandbox_id"]]["shutdown_time"]) != parse_time(r["expires_at"])],
           "A TTL refresh updated one but not the other (e.g. the patch failed). The next execution resyncs it.")
    report("problem", "DB operating_mode differs from the cluster's spec.operatingMode",
           [short(r["sandbox_id"]) for r in rows
            if r["sandbox_id"] in live and not r["deleted_at"] and live[r["sandbox_id"]]["operating_mode"] != r["operating_mode"]],
           "Paused or resumed outside the API (e.g. kubectl patch), or a pause/resume whose DB commit failed. "
           "Executions follow the DB. Call POST /sandboxes/{id}/pause or /resume to bring them back in line.")
    report("info", "Paused sandboxes",
           [short(r["sandbox_id"]) for r in rows if r["operating_mode"] == "Suspended" and not r["deleted_at"]],
           "Expected. Their pods are stopped; they expire at paused_at + paused_ttl_seconds unless resumed.")
    report("info", "Deleted sandboxes in their recovery window (files still downloadable)",
           [short(r["sandbox_id"]) for r in rows if r["deleted_at"]],
           f"Expected. The API's GC deletes the volume and row {RETENTION_HOURS}h after deletion or expiry.")
    retention_cutoff = now.timestamp() - RETENTION_HOURS * 3600
    report("warn", f"Rows past the {RETENTION_HOURS}h recovery window",
           [short(r["sandbox_id"]) for r in rows
            if any(parse_time(r[k]) and parse_time(r[k]).timestamp() < retention_cutoff for k in ("deleted_at", "expires_at"))],
           "The API's GC (every minute) should have removed these; check the sandbox-manager logs for `gc:` lines.")
    pvcs = pvc_names()
    if pvcs is not None:
        volumes = {r["volume_name"] for r in rows if r["volume_name"]}
        report("problem", "Rows whose volume (PVC) is missing",
               [short(r["sandbox_id"]) for r in rows if r["volume_name"] and r["volume_name"] not in pvcs],
               "Its files are gone (deleted outside the API?). DELETE /sandboxes/{id}?purge=true cleans the row.")
        report("problem", "Sandbox PVCs with no DB row",
               sorted(n for n in pvcs if n not in volumes),
               "Orphaned volumes using quota. Remove with: kubectl -n sandboxes delete pvc <name>")
    report("info", "Legacy sandboxes without a TTL", [short(r["sandbox_id"]) for r in rows if r["ttl_seconds"] is None],
           "Created before TTLs existed; they never expire.")
    stale = query(f"""SELECT execution_id::text FROM executions
                      WHERE status = 'running' AND started_at < now() - interval '{STALE_EXECUTION_SECONDS} seconds'""")
    report("problem", f"Executions stuck in `running` for over {STALE_EXECUTION_SECONDS}s",
           [short(e["execution_id"]) for e in stale],
           "The server stopped (restart/crash) mid-command, so the outcome was never recorded.")

    if not quiet:
        for level, title, items, explain in results:
            print(f"\n{colorize(level).ljust(9 + (len(colorize(level)) - len(level)))} {bold(title)}: {len(items)}")
            if items:
                print(textwrap.fill(", ".join(items), 100, initial_indent="          ", subsequent_indent="          "))
                print(dim(textwrap.fill(explain, 100, initial_indent="          ", subsequent_indent="          ")))
        print()
        print(green("All checks passed.") if problems == 0 else red(f"{problems} problem(s)."))
    return problems


def cmd_check(_: argparse.Namespace) -> None:
    sys.exit(1 if run_checks() else 0)


def cmd_sql(args: argparse.Namespace) -> None:
    first = args.query.lstrip().split(None, 1)[0].lower() if args.query.strip() else ""
    if first not in ("select", "with", "values", "table"):
        sys.exit("dbinspect: sql only runs read-only queries (SELECT / WITH / VALUES / TABLE)")
    rows = query(args.query)
    if args.json:
        print(json.dumps(rows, indent=2))
        return
    table(rows, list(rows[0].keys()) if rows else [], max_width=args.width)
    print(dim(f"\n({len(rows)} row{'s' if len(rows) != 1 else ''})"))


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="dbinspect", description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="\n".join(__doc__.split("\n\n")[1:3]))
    sub = parser.add_subparsers(dest="cmd")
    sub.add_parser("overview", help="tables, counts and health (default)").set_defaults(fn=cmd_overview)
    sub.add_parser("schema", help="tables, columns, keys and what they mean").set_defaults(fn=cmd_schema)
    p = sub.add_parser("sandboxes", help="every sandbox with live status and TTL")
    p.add_argument("--status", help="only this status (Ready, Expired, Missing, ...)")
    p.set_defaults(fn=cmd_sandboxes)
    p = sub.add_parser("sandbox", help="one sandbox: record, definition, executions")
    p.add_argument("id", help="sandbox id or unique prefix")
    p.add_argument("-n", "--limit", type=int, default=20)
    p.set_defaults(fn=cmd_sandbox)
    p = sub.add_parser("executions", help="recent executions")
    p.add_argument("-s", "--sandbox", help="only this sandbox (id or prefix)")
    p.add_argument("-n", "--limit", type=int, default=20)
    p.set_defaults(fn=cmd_executions)
    p = sub.add_parser("execution", help="one execution with full output")
    p.add_argument("id", help="execution id or unique prefix")
    p.set_defaults(fn=cmd_execution)
    sub.add_parser("check", help="consistency checks between DB and cluster (exit 1 on problems)").set_defaults(fn=cmd_check)
    p = sub.add_parser("sql", help="run a read-only SQL query")
    p.add_argument("query")
    p.add_argument("--json", action="store_true", help="print rows as JSON")
    p.add_argument("--width", type=int, default=60, help="max column width")
    p.set_defaults(fn=cmd_sql)

    args = parser.parse_args()
    (getattr(args, "fn", None) or cmd_overview)(args)


if __name__ == "__main__":
    main()
