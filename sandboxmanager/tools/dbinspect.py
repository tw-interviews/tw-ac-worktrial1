#!/usr/bin/env python3
"""Inspect and understand the SandboxManager database.

Everything is read-only: queries run through `kubectl exec` into the Postgres
pod with `default_transaction_read_only=on`, and cluster state is read with
`kubectl get`. Standard library only; works on the system Python 3.9.

    tools/dbinspect.py                  # overview: tables, counts, health
    tools/dbinspect.py schema           # tables, columns, keys, and what they mean
    tools/dbinspect.py sandboxes        # every sandbox with live cluster status and TTL
    tools/dbinspect.py sandbox <id>     # one sandbox: record, definition, executions
    tools/dbinspect.py executions [-s <sandbox-id>] [-n 20]
    tools/dbinspect.py execution <id>   # one execution with full output
    tools/dbinspect.py check            # consistency checks between DB and cluster
    tools/dbinspect.py sql "SELECT ..." # ad-hoc read-only query

Ids may be abbreviated to a unique prefix (e.g. the first 8 characters).
Environment: DB_NAMESPACE (webapp), DB_POD (postgres-0), DB_USER (webapp),
DB_NAME (webapp), KUBE_CONTEXT (current context).
"""

